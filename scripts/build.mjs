import { readdir, readFile, writeFile, mkdir, copyFile, rm, lstat } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, relative, join, basename } from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const output = resolve(root, 'public');
export async function build() {
  // Only clear our explicitly named, generated directory. Never follow a link.
  if (dirname(output) !== root || basename(output) !== 'public') throw new Error('Unsafe output path');
  if (existsSync(output)) {
    if ((await lstat(output)).isSymbolicLink() || !existsSync(join(output, '.khonshu-build'))) throw new Error('Refusing to overwrite an unrelated public directory');
    await rm(output, { recursive: true, force: true });
  }
  await mkdir(output, { recursive: true }); await writeFile(join(output, '.khonshu-build'), 'Generated by scripts/build.mjs\n');
  const files = ['index.html', 'remote.html', 'manifest.webmanifest', '_headers'];
  async function walk(folder) {
    for (const entry of await readdir(join(root, folder), { withFileTypes: true })) {
      const name = folder + '/' + entry.name;
      if (entry.isSymbolicLink()) throw new Error('Asset directories must not contain links');
      if (entry.isDirectory()) await walk(name); else files.push(name);
    }
  }
  for (const folder of ['js', 'css', 'data', 'icons']) await walk(folder);
  files.sort(); const hash = createHash('sha256');
  for (const name of files) {
    if (name !== 'js/version.js') hash.update(name).update(await readFile(join(root, name)));
    const target = join(output, name); await mkdir(dirname(target), { recursive: true }); await copyFile(join(root, name), target);
  }
  const swSource = await readFile(join(root, 'sw.js'), 'utf8'); hash.update(swSource);
  const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
  const ciCommit = [process.env.GITHUB_SHA, process.env.WORKERS_CI_COMMIT_SHA].find(value => /^[a-f0-9]{7,64}$/i.test(value || ''));
  let commit = 'local';
  try {
    commit = ciCommit?.slice(0, 7) || execFileSync('git', ['rev-parse', '--short=7', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
    if (!ciCommit && execFileSync('git', ['status', '--porcelain'], { cwd: root, encoding: 'utf8' }).trim()) commit += '-dirty';
  } catch {}
  const revision = hash.update(pkg.version).update(commit).digest('hex').slice(0, 16);
  const metadata = { version: pkg.version, commit, revision, builtAt: new Date().toISOString() };
  await writeFile(join(output, 'js/version.js'), 'window.KHONSHU_BUILD = ' + JSON.stringify(metadata) + ';\n');
  const assets = files.filter(f => f !== '_headers').map(f => './' + f);
  await writeFile(join(output, 'sw.js'), swSource.replace("const VERSION = 'dev';", 'const VERSION = ' + JSON.stringify(revision) + ';').replace('const ASSETS = [];', 'const ASSETS = ' + JSON.stringify(assets) + ';'));
  console.log(`Built Khonshu ${pkg.version} (${commit}); ${assets.length} offline assets in ${relative(root, output)}`);
  return metadata;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await build();
