// Shared collection on the sky and phone remote. External sounds open their
// official players; no third-party audio or scripts are loaded into Khonshu.
(() => {
'use strict';

const SOURCES = [
  { id: 'khonshu', name: 'Khonshu ambient · offline',
    description: 'Slow ambient music generated by Khonshu. Use Sound on, Volume and Sleep timer.' },
  { id: 'black-hole', name: 'myNoise · Black Hole',
    description: 'An adjustable space soundscape. Try the Serenity or Floating preset.',
    url: 'https://mynoise.net/NoiseMachines/intergalacticSoundscapeGenerator.php' },
  { id: 'drone-zone', name: 'SomaFM · Drone Zone',
    description: 'Atmospheric drones and space music with minimal beats.',
    url: 'https://somafm.com/dronezone/' },
  { id: 'deep-space-one', name: 'SomaFM · Deep Space One',
    description: 'Deep ambient electronic and space music, with more rhythm than Drone Zone.',
    url: 'https://somafm.com/deepspaceone/' },
];
const STORE_KEY = 'khonshu-sound-collection';
const widgets = [];
function savedChoice() {
  try { return localStorage.getItem(STORE_KEY); } catch { return null; }
}

for (const container of document.querySelectorAll('[data-sound-collection]')) {
  const label = document.createElement('label');
  const title = document.createElement('span'); title.textContent = 'Sound';
  const select = document.createElement('select'); select.id = 'sound-source';
  label.htmlFor = select.id; label.append(title, select);
  for (const source of SOURCES) select.add(new Option(source.name, source.id));
  const description = document.createElement('p'); description.className = 'sound-description';
  description.id = 'sound-description'; select.setAttribute('aria-describedby', description.id);
  const link = document.createElement('a'); link.className = 'sound-player';
  link.target = '_blank'; link.rel = 'noopener noreferrer';
  const note = document.createElement('p'); note.className = 'sound-note';
  note.textContent = 'Opens a separate player. Use its playback and volume controls. Khonshu’s sound toggle and timer control only Khonshu audio.';
  container.append(label, description, link, note);

  function show(id) {
    const source = SOURCES.find(s => s.id === id) || SOURCES[0];
    select.value = source.id; description.textContent = source.description;
    link.hidden = note.hidden = !source.url;
    if (source.url) {
      link.href = source.url;
      link.textContent = 'Open ' + source.name + ' ↗';
    } else link.removeAttribute('href');
  }
  select.addEventListener('change', () => {
    show(select.value);
    try { localStorage.setItem(STORE_KEY, select.value); } catch {}
  });
  widgets.push(show); show(savedChoice());
}
window.addEventListener('storage', event => {
  if (event.key === STORE_KEY) for (const show of widgets) show(event.newValue);
});
})();
